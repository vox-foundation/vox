// Slide data for the two frontpage carousels. Keep claims checkable: each `cli` is a real command,
// each `code` block is real tool output (see `codeNote`), and counts come from generated catalogs.

export interface CarouselSlide {
  id: string;
  tab: string;
  badge: string;
  title: string;
  /** What it is. */
  what: string;
  /** Why it is built this way. */
  why: string;
  /** What it gives an AI agent that writes or runs code. */
  ai: string;
  /** What it gives the person using it. */
  users: string;
  cli: string;
  linkHref: string;
  linkLabel: string;
  /** Axis capture base name under /assets/axis/hd/ (light and dark, 1280 and 2560 wide). */
  image?: { base: string; alt: string };
  /** Real terminal or generated output shown instead of a capture. */
  code?: { text: string; note: string };
}

