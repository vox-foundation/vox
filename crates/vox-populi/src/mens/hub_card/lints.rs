/// The heading id the docs site gives `heading` (a port of github-slugger: lowercase, drop
/// everything but letters, digits, `-`, `_` and spaces, then spaces become `-`).
pub(super) fn slug(heading: &str) -> String {
    heading
        .trim()
        .to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric() || matches!(c, ' ' | '-' | '_'))
        .map(|c| if c == ' ' { '-' } else { c })
        .collect()
}

/// The ids of every `##` or deeper heading of a docs page (repeats get `-1`, `-2`, as github-slugger does).
pub(super) fn doc_slugs(md: &str) -> BTreeSet<String> {
    let (_, lines) = split_fences(split_frontmatter(md).1);
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    let mut ids = BTreeSet::new();
    for line in lines {
        let hashes = line.chars().take_while(|&c| c == '#').count();
        let Some(text) = line.get(hashes..).and_then(|t| t.strip_prefix(' ')) else {
            continue;
        };
        if !(2..=6).contains(&hashes) {
            continue;
        }
        let base = slug(text.trim_end_matches('#'));
        let n = seen.entry(base.clone()).or_default();
        ids.insert(if *n == 0 { base } else { format!("{base}-{n}") });
        *n += 1;
    }
    ids
}

/// The `#fragment` of every link to the docs page on a card.
pub(super) fn card_anchors(card: &str) -> Vec<String> {
    let prefix = format!("{DOCS}#");
    card.match_indices(&prefix)
        .map(|(i, _)| {
            card[i + prefix.len()..]
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_'))
                .collect()
        })
        .collect()
}

/// What a card is, which decides the metadata rules it falls under.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) enum Kind {
    Trained,
    NotTrained,
    Index,
}

/// `name` is the repo name or golden file stem; the status line tells trained from not trained.
pub(super) fn kind_of(name: &str, card: &str) -> Kind {
    if name.ends_with("index") {
        Kind::Index
    } else if card.contains("[not trained](") {
        Kind::NotTrained
    } else {
        Kind::Trained
    }
}

pub(super) fn frontmatter_of(card: &str) -> Option<Value> {
    serde_yaml::from_str(split_frontmatter(card).0).ok()
}

fn seq(v: &Value) -> &[Value] {
    v.as_sequence().map(Vec::as_slice).unwrap_or_default()
}

fn strs(v: &Value) -> Vec<String> {
    let strings = seq(v).iter().filter_map(|x| x.as_str());
    strings.map(String::from).collect()
}

fn need(v: &Value, keys: &Value, at: &str, errs: &mut Vec<String>) {
    for k in strs(keys) {
        if v.get(k.as_str()).is_none() {
            errs.push(format!("{at}: missing `{k}`"));
        }
    }
}

/// Every way `fm` breaks the local Hub metadata `rules` (hf-metadata-rules.v1.yaml) for a card
/// of this `kind`. No network.
pub(super) fn check_hf_metadata(fm: &Value, rules: &Value, kind: Kind) -> Vec<String> {
    let mut e = Vec::new();
    let Some(map) = fm.as_mapping() else {
        return vec!["frontmatter is not a mapping".into()];
    };
    let known = strs(&rules["known_keys"]);
    for k in map.keys().filter_map(Value::as_str) {
        if !known.iter().any(|x| x == k) {
            e.push(format!("frontmatter: unknown key `{k}`"));
        }
    }
    let which = if kind == Kind::Index {
        "index"
    } else {
        "model_card"
    };
    need(fm, &rules["required"][which], "frontmatter", &mut e);
    let tags = strs(&fm["tags"]);
    if fm
        .get("tags")
        .is_some_and(|t| t.as_sequence().is_none_or(|s| s.len() != tags.len()))
    {
        e.push("tags: not a list of strings".into());
    }
    if let Some(bm) = fm.get("base_model") {
        let forbid = rules["base_model"]["forbid_char"].as_str().unwrap_or("@");
        match bm.as_str() {
            Some(id) if !id.contains(forbid) && id.split('/').count() == 2 => {}
            _ => e.push(format!(
                "base_model: want owner/name without `{forbid}`, got {bm:?}"
            )),
        }
    }
    if let Some(rel) = fm.get("base_model_relation")
        && !strs(&rules["base_model_relation"])
            .iter()
            .any(|r| Some(r.as_str()) == rel.as_str())
    {
        e.push(format!(
            "base_model_relation: {rel:?} is not a Hub relation"
        ));
    }
    let has = |prefix: &str| tags.iter().filter(|t| t.starts_with(prefix)).count();
    match kind {
        Kind::Trained => {
            for p in strs(&rules["tags"]["trained_require_prefix"]) {
                if has(&p) != 1 {
                    e.push(format!(
                        "tags: a trained card needs exactly one `{p}` tag, has {}",
                        has(&p)
                    ));
                }
            }
        }
        Kind::NotTrained => {
            for t in strs(&rules["tags"]["not_trained_require"]) {
                if !tags.contains(&t) {
                    e.push(format!("tags: a not-trained card needs `{t}`"));
                }
            }
        }
        Kind::Index => {}
    }
    if let Some(mi) = fm.get("model-index") {
        check_model_index(mi, &rules["model_index"], &mut e);
    }
    e
}

fn check_model_index(mi: &Value, r: &Value, e: &mut Vec<String>) {
    let Some(entries) = mi.as_sequence() else {
        return e.push("model-index: not a list".into());
    };
    for entry in entries {
        need(entry, &r["entry"], "model-index entry", e);
        for res in seq(&entry["results"]) {
            need(res, &r["result"], "model-index result", e);
            need(&res["task"], &r["task"], "model-index task", e);
            need(&res["dataset"], &r["dataset"], "model-index dataset", e);
            let metrics = seq(&res["metrics"]);
            if metrics.is_empty() {
                e.push("model-index result: no metrics".into());
            }
            for m in metrics {
                need(m, &r["metric"], "model-index metric", e);
                if m.get("value").is_some_and(|v| !v.is_number()) {
                    e.push(format!(
                        "model-index metric: value must be a number, got {:?}",
                        m["value"]
                    ));
                }
            }
        }
    }
}

/// How many `vox` fences a card has, and why each one that fails the compiler front end does.
pub(super) fn vox_failures(card: &str) -> (usize, Vec<String>) {
    let blocks: Vec<_> = split_fences(split_frontmatter(card).1)
        .0
        .into_iter()
        .filter(|(info, _)| info.split_whitespace().next() == Some("vox"))
        .collect();
    let bad = blocks
        .iter()
        .filter_map(|(_, body)| vox_block_ok(body).err())
        .collect();
    (blocks.len(), bad)
}

