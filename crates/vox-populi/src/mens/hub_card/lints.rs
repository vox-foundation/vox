//! Lints over rendered cards (spec section 7, phase 339 plan 09). Test-only.
//!
//! The duplicate-sentence lint implements, and only, the rule on docs/src/reference/mens-models.md
//! under "How the cards are made": per card drop the frontmatter, fenced blocks and the footer;
//! units are headings, list items, table rows and paragraphs; sentences split after `.`, `?` or
//! `!` before a space or the unit end; a sentence of four or more words found twice fails. A
//! failing card is fixed in its template, never here.
//!
//! The real rendered cards are checked with:
//! `VOX_HUB_CARDS_DIR=<abs path to mens/runs/hub_cards> cargo test -p vox-populi --features
//! mens-hf-hub --lib lints_hold_on_rendered_cards_dir -- --ignored`.

use std::collections::{BTreeMap, BTreeSet};

use serde_yaml::Value;

use super::card_facts::DOCS;
use super::tests::support::vox_block_ok;

/// Anchor of the footer line both templates end with; the footer is the rule's one exception.
pub(super) const FOOTER_MARKER: &str = "generated by `vox mens hub sync`";

/// Split `text` at fenced code blocks (CommonMark: a fence closes on a run at least as long as its
/// opener). Returns `(info string, body)` per block and the other lines, a blank line standing in
/// for each block.
pub(super) fn split_fences(text: &str) -> (Vec<(String, String)>, Vec<&str>) {
    let (mut blocks, mut rest) = (Vec::new(), Vec::new());
    let mut open: Option<(usize, String, String)> = None;
    for line in text.lines() {
        let t = line.trim_start();
        let run = t.chars().take_while(|&c| c == '`').count();
        if let Some((n, info, body)) = open.as_mut() {
            if run >= *n && t[run..].trim().is_empty() {
                blocks.push((std::mem::take(info), std::mem::take(body)));
                open = None;
            } else {
                body.push_str(line);
                body.push('\n');
            }
        } else if run >= 3 {
            open = Some((run, t[run..].trim().to_string(), String::new()));
            rest.push("");
        } else {
            rest.push(line);
        }
    }
    blocks.extend(open.map(|(_, info, body)| (info, body)));
    (blocks, rest)
}

/// `(frontmatter YAML, body)`; the frontmatter is empty when the card has none.
pub(super) fn split_frontmatter(card: &str) -> (&str, &str) {
    let Some(rest) = card.strip_prefix("---\n") else {
        return ("", card);
    };
    rest.split_once("\n---\n").unwrap_or(("", card))
}

fn is_item(t: &str) -> bool {
    t.starts_with("- ")
        || t.starts_with("* ")
        || t.split_once(". ")
            .is_some_and(|(n, _)| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
}

/// Headings, list items, table rows and paragraphs (consecutive plain lines joined).
pub(super) fn units(lines: &[&str]) -> Vec<String> {
    let (mut out, mut para) = (Vec::new(), String::new());
    for line in lines {
        let t = line.trim();
        let single = t.starts_with('#') || t.starts_with('|');
        if (t.is_empty() || single || is_item(t)) && !para.is_empty() {
            out.push(std::mem::take(&mut para));
        }
        if t.is_empty() {
            continue;
        }
        if single {
            out.push(t.to_string());
        } else {
            if !para.is_empty() {
                para.push(' ');
            }
            para.push_str(t);
        }
    }
    out.extend((!para.is_empty()).then_some(para));
    out
}

/// Split after `.`, `?` or `!` when a space or the end of the unit follows.
fn split_sentences(unit: &str) -> Vec<&str> {
    let (mut out, mut start) = (Vec::new(), 0);
    for (i, c) in unit.char_indices() {
        if matches!(c, '.' | '?' | '!')
            && unit[i + 1..].chars().next().is_none_or(char::is_whitespace)
        {
            out.push(&unit[start..=i]);
            start = i + 1;
        }
    }
    out.extend((start < unit.len()).then(|| &unit[start..]));
    out
}

/// Link text kept and URL dropped, backticks and emphasis markers removed, pipes to spaces,
/// lowercased, whitespace collapsed, trailing punctuation dropped.
pub(super) fn normalize(s: &str) -> String {
    let (mut text, mut rest) = (String::new(), s);
    while let Some(i) = rest.find('[') {
        text.push_str(&rest[..i]);
        let after = &rest[i + 1..];
        let link = after
            .find("](")
            .and_then(|j| after[j + 2..].find(')').map(|k| (j, j + 2 + k)));
        match link {
            Some((j, k)) if !after[..j].contains('[') => {
                text.push_str(&after[..j]);
                rest = &after[k + 1..];
            }
            _ => {
                text.push('[');
                rest = after;
            }
        }
    }
    text.push_str(rest);
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        let edge = i == 0
            || !chars[i - 1].is_alphanumeric()
            || chars.get(i + 1).is_none_or(|n| !n.is_alphanumeric());
        match c {
            '`' | '*' => {}
            '_' if edge => {}
            '|' => out.push(' '),
            _ => out.extend(c.to_lowercase()),
        }
    }
    let joined = out.split_whitespace().collect::<Vec<_>>().join(" ");
    joined
        .trim_end_matches(|c: char| c.is_ascii_punctuation() || c.is_whitespace())
        .to_string()
}

/// A word is a whitespace-separated token with at least one letter or digit.
pub(super) fn word_count(s: &str) -> usize {
    s.split_whitespace()
        .filter(|w| w.chars().any(char::is_alphanumeric))
        .count()
}

/// The normalized sentences of one card under the docs rule (frontmatter, fences, footer dropped).
pub(super) fn sentences(card: &str) -> Vec<String> {
    let (_, mut lines) = split_fences(split_frontmatter(card).1);
    if let Some(i) = lines.iter().rposition(|l| !l.trim().is_empty())
        && lines[i].contains(FOOTER_MARKER)
    {
        lines.truncate(i);
    }
    units(&lines)
        .iter()
        .flat_map(|u| split_sentences(u))
        .map(normalize)
        .filter(|s| !s.is_empty())
        .collect()
}

/// Every sentence of four or more words found twice in the set, with the card of each occurrence.
pub(super) fn duplicates(cards: &[(String, String)]) -> Vec<(String, Vec<String>)> {
    let mut seen: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (name, card) in cards {
        for s in sentences(card) {
            if word_count(&s) >= 4 {
                seen.entry(s).or_default().push(name.clone());
            }
        }
    }
    seen.into_iter().filter(|(_, v)| v.len() > 1).collect()
}

