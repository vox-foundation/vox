//! `vox ci crate-api-sync` — automated workspace crate API documentation generator (GEN-04).

use std::fs;
use std::path::Path;

use anyhow::{Context, Result, anyhow};
use cargo_metadata::MetadataCommand;
use vox_bounded_fs::read_utf8_path_capped;

const WARNING_BLOCK: &str = r#"<!--
  ========================================================================
  🛑 🛑 🛑 AUTO-GENERATED FILE. DO NOT EDIT THIS FILE MANUALLY! 🛑 🛑 🛑
  ========================================================================
  
  ATTENTION AI AGENTS, LLMs, AND BOTS:
  This file is automatically generated by `vox ci crate-api-sync`.
  Any manual edits you make here WILL BE OVERWRITTEN AND LOST.
  
  DO NOT USE `replace_file_content` or similar tools on this file.
  ========================================================================
-->"#;

fn normalize_lf(s: &str) -> String {
    s.replace("\r\n", "\n").replace('\r', "\n")
}

fn escape_table_cell(s: &str) -> String {
    s.replace('\r', "")
        .replace('\n', " ")
        .replace('|', "\\|")
        .trim()
        .to_string()
}

#[derive(Default, Debug)]
struct ParsedPublicSurface {
    crate_docs: Vec<String>,
    modules: Vec<(String, String)>,
    structs: Vec<(String, String)>,
    enums: Vec<(String, String)>,
    traits: Vec<(String, String)>,
    functions: Vec<(String, String)>,
    types: Vec<(String, String)>,
    constants: Vec<(String, String)>,
}

fn parse_lib_rs(source: &str) -> ParsedPublicSurface {
    let mut surface = ParsedPublicSurface::default();
    let mut current_doc = Vec::new();

    for line in source.lines() {
        let trimmed = line.trim();

        if let Some(doc) = trimmed.strip_prefix("//!") {
            surface.crate_docs.push(doc.trim().to_string());
            continue;
        }

        if let Some(doc) = trimmed.strip_prefix("///") {
            current_doc.push(doc.trim().to_string());
            continue;
        }

        if trimmed.starts_with("//") || trimmed.is_empty() || trimmed.starts_with("#[") {
            if trimmed.is_empty() {
                current_doc.clear();
            }
            continue;
        }

        // Match public items
        if trimmed.starts_with("pub ") {
            let doc_text = current_doc.join(" ");
            current_doc.clear();

            let after_pub = trimmed.strip_prefix("pub ").unwrap_or("").trim();
            // strip pub(crate), pub(super), etc.
            if after_pub.starts_with('(') {
                continue;
            }

            if let Some(rest) = after_pub.strip_prefix("mod ") {
                let name = rest.split(&[' ', ';', '{'][..]).next().unwrap_or("").trim();
                if !name.is_empty() {
                    surface.modules.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub.strip_prefix("struct ") {
                let name = rest
                    .split(&[' ', '<', ';', '{', '('][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.structs.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub.strip_prefix("enum ") {
                let name = rest
                    .split(&[' ', '<', ';', '{'][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.enums.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub.strip_prefix("trait ") {
                let name = rest
                    .split(&[' ', '<', ':', ';', '{'][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.traits.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub
                .strip_prefix("fn ")
                .or_else(|| after_pub.strip_prefix("async fn "))
                .or_else(|| after_pub.strip_prefix("const fn "))
                .or_else(|| after_pub.strip_prefix("unsafe fn "))
            {
                let name = rest
                    .split(&[' ', '<', '(', ';', '{'][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.functions.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub.strip_prefix("type ") {
                let name = rest
                    .split(&[' ', '<', '=', ';'][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.types.push((name.to_string(), doc_text));
                }
            } else if let Some(rest) = after_pub.strip_prefix("const ") {
                let name = rest
                    .split(&[' ', ':', ';', '='][..])
                    .next()
                    .unwrap_or("")
                    .trim();
                if !name.is_empty() {
                    surface.constants.push((name.to_string(), doc_text));
                }
            }
        } else {
            current_doc.clear();
        }
    }

    surface
}

fn write_or_verify_file(out_path: &Path, rendered: &str, write: bool) -> Result<()> {
    if write {
        if let Some(parent) = out_path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("create dir {}", parent.display()))?;
        }
        fs::write(out_path, normalize_lf(rendered))
            .with_context(|| format!("write {}", out_path.display()))?;
        return Ok(());
    }
    if !out_path.is_file() {
        return Err(anyhow!(
            "missing {}; run `vox ci crate-api-sync --write`",
            out_path.display()
        ));
    }
    let existing =
        read_utf8_path_capped(out_path).with_context(|| format!("read {}", out_path.display()))?;
    if normalize_lf(&existing) != normalize_lf(rendered) {
        return Err(anyhow!(
            "{} is stale; run `vox ci crate-api-sync --write` from the repo root",
            out_path.display()
        ));
    }
    Ok(())
}

/// Generate or verify Markdown reference pages for workspace crates under `docs/src/api/`.
pub fn run(repo_root: &Path, write: bool) -> Result<()> {
    let manifest_path = repo_root.join("Cargo.toml");
    let metadata = MetadataCommand::new()
        .manifest_path(&manifest_path)
        .no_deps()
        .exec()
        .context("run `cargo metadata`")?;

    let api_dir = repo_root.join("docs/src/api");
    if write && !api_dir.exists() {
        fs::create_dir_all(&api_dir).context("create docs/src/api")?;
    }

    let mut packages: Vec<_> = metadata
        .workspace_packages()
        .into_iter()
        .filter(|p| p.name != "workspace-hack")
        .collect();
    packages.sort_by(|a, b| a.name.cmp(&b.name));

    let mut index_entries = Vec::new();

    for pkg in &packages {
        let pkg_name = &pkg.name;
        let version = &pkg.version.to_string();
        let description = pkg
            .description
            .as_deref()
            .unwrap_or("No description provided.")
            .trim();
        let clean_desc = escape_table_cell(description);

        index_entries.push((pkg_name.clone(), version.clone(), clean_desc.clone()));

        let manifest_dir = pkg.manifest_path.parent().expect("pkg manifest dir");
        let lib_path = manifest_dir.join("src/lib.rs");
        let main_path = manifest_dir.join("src/main.rs");

        let (entry_file, is_lib) = if lib_path.exists() {
            (lib_path.into_std_path_buf(), true)
        } else if main_path.exists() {
            (main_path.into_std_path_buf(), false)
        } else {
            continue;
        };

        let source = read_utf8_path_capped(&entry_file).unwrap_or_default();
        let surface = parse_lib_rs(&source);

        let mut doc = String::new();
        doc.push_str("---\n");
        doc.push_str(&format!(
            "title: \"{} API Reference (generated)\"\n",
            pkg_name
        ));
        doc.push_str(&format!("description: \"{}\"\n", clean_desc));
        doc.push_str("category: \"API Reference — Crates\"\n");
        doc.push_str("status: current\n");
        doc.push_str("---\n\n");
        doc.push_str(WARNING_BLOCK);
        doc.push_str("\n\n");
        doc.push_str(&format!("# `{}`\n\n", pkg_name));
        doc.push_str(&format!(
            "**Crate:** `{}` · **Version:** `{}` · **Target:** {}\n\n",
            pkg_name,
            version,
            if is_lib {
                "Library (`lib.rs`)"
            } else {
                "Binary (`main.rs`)"
            }
        ));

        if !clean_desc.is_empty() {
            doc.push_str(&format!("{}\n\n", clean_desc));
        }

        if !surface.crate_docs.is_empty() {
            doc.push_str("## Crate Overview\n\n");
            for line in &surface.crate_docs {
                doc.push_str(line);
                doc.push('\n');
            }
            doc.push_str("\n\n");
        }

        // Features
        if !pkg.features.is_empty() {
            doc.push_str("## Features\n\n");
            doc.push_str("| Feature | Default / Enables |\n");
            doc.push_str("|---|---|\n");
            let mut feats: Vec<_> = pkg.features.iter().collect();
            feats.sort_by(|a, b| a.0.cmp(b.0));
            for (feat, enables) in feats {
                let en_str = if enables.is_empty() {
                    "—".to_string()
                } else {
                    enables.join(", ")
                };
                doc.push_str(&format!(
                    "| `{}` | {} |\n",
                    feat,
                    escape_table_cell(&en_str)
                ));
            }
            doc.push_str("\n");
        }

        // Workspace dependencies
        let ws_deps: Vec<_> = pkg
            .dependencies
            .iter()
            .filter(|d| d.path.is_some())
            .collect();
        if !ws_deps.is_empty() {
            doc.push_str("## Workspace Dependencies\n\n");
            doc.push_str("| Dependency | Kind |\n");
            doc.push_str("|---|---|\n");
            for dep in ws_deps {
                doc.push_str(&format!(
                    "| [`{}`](./{}.generated.md) | {:?} |\n",
                    dep.name, dep.name, dep.kind
                ));
            }
            doc.push_str("\n");
        }

        // Public surface items
        let has_public_items = !surface.modules.is_empty()
            || !surface.structs.is_empty()
            || !surface.enums.is_empty()
            || !surface.traits.is_empty()
            || !surface.functions.is_empty()
            || !surface.types.is_empty()
            || !surface.constants.is_empty();

        if has_public_items {
            doc.push_str("## Public API Surface\n\n");

            if !surface.modules.is_empty() {
                doc.push_str("### Modules\n\n");
                doc.push_str("| Module | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.modules {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.structs.is_empty() {
                doc.push_str("### Structs\n\n");
                doc.push_str("| Struct | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.structs {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.enums.is_empty() {
                doc.push_str("### Enums\n\n");
                doc.push_str("| Enum | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.enums {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.traits.is_empty() {
                doc.push_str("### Traits\n\n");
                doc.push_str("| Trait | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.traits {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.functions.is_empty() {
                doc.push_str("### Functions\n\n");
                doc.push_str("| Function | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.functions {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.types.is_empty() {
                doc.push_str("### Types\n\n");
                doc.push_str("| Type | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.types {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }

            if !surface.constants.is_empty() {
                doc.push_str("### Constants\n\n");
                doc.push_str("| Constant | Description |\n");
                doc.push_str("|---|---|\n");
                for (name, desc) in &surface.constants {
                    let d = if desc.is_empty() { "—" } else { desc };
                    doc.push_str(&format!("| `{}` | {} |\n", name, escape_table_cell(d)));
                }
                doc.push_str("\n");
            }
        }

        let out_file = api_dir.join(format!("{}.generated.md", pkg_name));
        write_or_verify_file(&out_file, &doc, write)?;
    }

    // Index page
    let mut index_doc = String::new();
    index_doc.push_str("---\n");
    index_doc.push_str("title: \"Workspace Crate API Index (generated)\"\n");
    index_doc.push_str("description: \"Machine-derived directory of all first-party crates in the Vox workspace with public API documentation.\"\n");
    index_doc.push_str("category: \"API Reference — Crates\"\n");
    index_doc.push_str("status: current\n");
    index_doc.push_str("---\n\n");
    index_doc.push_str(WARNING_BLOCK);
    index_doc.push_str("\n\n# Workspace Crate API Index (generated)\n\n");
    index_doc.push_str("**Intended readers:** Platform engineers, crate contributors, and developers integrating with Vox internal and external crates.\n\n");
    index_doc.push_str(&format!(
        "**Total Workspace Crates:** {}\n\n",
        index_entries.len()
    ));
    index_doc.push_str("| Crate | Version | Description |\n");
    index_doc.push_str("|---|---|---|\n");
    for (name, ver, desc) in index_entries {
        index_doc.push_str(&format!(
            "| [`{}`](./{}.generated.md) | `{}` | {} |\n",
            name, name, ver, desc
        ));
    }
    index_doc.push('\n');

    let index_file = api_dir.join("index.generated.md");
    write_or_verify_file(&index_file, &index_doc, write)?;

    println!("crate-api-sync OK ({} crates)", packages.len());
    Ok(())
}
