//! Render the GUI KB facet TypeScript type from the committed facet JSON Schema (KB Phase 4, D-02).
//!
//! Reads `contracts/documentation/kb-facets.v1.schema.json` (itself golden-tested against the
//! Rust `Facets` type), so this crate needs no `vox-kb-facets` edge. The renderer is closed over
//! the shapes the schema uses and fails on anything else rather than emitting a loose type.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Result, bail};
use serde_json::Value;

pub const SCHEMA_REL: &str = "contracts/documentation/kb-facets.v1.schema.json";
pub const OUT_REL: &str = "crates/vox-gui/ui/src/generated/kbFacets.generated.ts";

const HEADER: &str = "// AUTO-GENERATED by `vox ci config-gui-codegen --kb-facets` from contracts/documentation/kb-facets.v1.schema.json. DO NOT EDIT.";

fn screaming_snake(name: &str) -> String {
    let mut s = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            s.push('_');
        }
        s.push(c.to_ascii_uppercase());
    }
    s
}

fn ident(name: &str, path: &str) -> Result<()> {
    let mut cs = name.chars();
    let ok = cs
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && cs.all(|c| c.is_ascii_alphanumeric() || c == '_');
    if !ok {
        bail!("kb-facets TS: `{path}` is not a plain identifier");
    }
    Ok(())
}

/// Returns `(ts type, nullable)` for one property schema.
fn ts_type(v: &Value, path: &str) -> Result<(String, bool)> {
    if v.get("enum").is_some() || v.get("const").is_some() {
        bail!("kb-facets TS: unsupported inline enum/const at `{path}` (declare a definition)");
    }
    if let Some(r) = v.get("$ref").and_then(Value::as_str) {
        let name = r
            .strip_prefix("#/definitions/")
            .or_else(|| r.strip_prefix("#/$defs/"))
            .ok_or_else(|| anyhow::anyhow!("kb-facets TS: unsupported $ref `{r}` at `{path}`"))?;
        return Ok((name.to_string(), false));
    }
    if let Some(members) = v
        .get("anyOf")
        .or_else(|| v.get("oneOf"))
        .and_then(Value::as_array)
    {
        let is_null = |m: &&Value| m.get("type").and_then(Value::as_str) == Some("null");
        let rest: Vec<&Value> = members.iter().filter(|m| !is_null(m)).collect();
        if rest.len() != 1 || rest.len() == members.len() {
            bail!("kb-facets TS: unsupported anyOf/oneOf at `{path}` (only `T | null`)");
        }
        return Ok((ts_type(rest[0], path)?.0, true));
    }
    match v.get("type") {
        Some(Value::String(t)) => match t.as_str() {
            "string" => Ok(("string".into(), false)),
            "boolean" => Ok(("boolean".into(), false)),
            "array" => {
                let items = v.get("items").ok_or_else(|| {
                    anyhow::anyhow!("kb-facets TS: array at `{path}` has no `items`")
                })?;
                let (t, nullable) = ts_type(items, path)?;
                if nullable {
                    bail!("kb-facets TS: nullable array items at `{path}` unsupported");
                }
                Ok((format!("{t}[]"), false))
            }
            other => bail!("kb-facets TS: unsupported type `{other}` at `{path}`"),
        },
        Some(Value::Array(ts)) => {
            let rest: Vec<&Value> = ts.iter().filter(|t| t.as_str() != Some("null")).collect();
            if rest.len() != 1 || rest.len() == ts.len() {
                bail!("kb-facets TS: unsupported type union at `{path}` (only `[T, \"null\"]`)");
            }
            let mut inner = v.clone();
            inner["type"] = rest[0].clone();
            Ok((ts_type(&inner, path)?.0, true))
        }
        _ => bail!("kb-facets TS: unsupported schema shape at `{path}`"),
    }
}

fn doc_comment(v: &Value, indent: &str) -> String {
    match v.get("description").and_then(Value::as_str) {
        Some(d) => format!(
            "{indent}/** {} */\n",
            d.replace("*/", "* /").replace('\n', " ")
        ),
        None => String::new(),
    }
}

fn render_interface(name: &str, obj: &Value) -> Result<String> {
    ident(name, name)?;
    let props = obj
        .get("properties")
        .and_then(Value::as_object)
        .ok_or_else(|| anyhow::anyhow!("kb-facets TS: `{name}` has no `properties`"))?;
    let required: Vec<&str> = obj
        .get("required")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut s = doc_comment(obj, "");
    writeln!(s, "export interface {name} {{")?;
    for (k, pv) in props {
        let path = format!("{name}.{k}");
        ident(k, &path)?;
        let (ty, nullable) = ts_type(pv, &path)?;
        let opt = if required.contains(&k.as_str()) {
            ""
        } else {
            "?"
        };
        let null = if nullable { " | null" } else { "" };
        s.push_str(&doc_comment(pv, "  "));
        writeln!(s, "  {k}{opt}: {ty}{null};")?;
    }
    s.push_str("}\n");
    Ok(s)
}

fn render_enum(name: &str, def: &Value) -> Result<String> {
    ident(name, name)?;
    let vals: Vec<&str> = if let Some(e) = def.get("enum").and_then(Value::as_array) {
        e.iter().filter_map(Value::as_str).collect()
    } else if let Some(o) = def.get("oneOf").and_then(Value::as_array) {
        o.iter()
            .filter_map(|m| m.get("const").and_then(Value::as_str))
            .collect()
    } else {
        Vec::new()
    };
    let declared = def
        .get("enum")
        .or_else(|| def.get("oneOf"))
        .and_then(Value::as_array)
        .map_or(0, Vec::len);
    if vals.is_empty() || vals.len() != declared {
        bail!("kb-facets TS: `{name}` is not a closed string enum");
    }
    let list = vals
        .iter()
        .map(|v| format!("{v:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let c = screaming_snake(name);
    Ok(format!(
        "{}export const {c}_VALUES = [{list}] as const;\nexport type {name} = (typeof {c}_VALUES)[number];\n",
        doc_comment(def, "")
    ))
}

/// Render the TS module for a facet JSON Schema. Deterministic; fails on unsupported shapes.
pub fn render_kb_facets_ts(schema: &Value) -> Result<String> {
    let mut out = format!("{HEADER}\n");
    let defs = schema
        .get("definitions")
        .or_else(|| schema.get("$defs"))
        .and_then(Value::as_object);
    if let Some(defs) = defs {
        let mut names: Vec<&String> = defs.keys().collect();
        names.sort();
        for name in names {
            let def = &defs[name];
            let block = if def.get("type").and_then(Value::as_str) == Some("object") {
                render_interface(name, def)?
            } else {
                render_enum(name, def)?
            };
            out.push('\n');
            out.push_str(&block);
        }
    }
    let root_name = schema
        .get("title")
        .and_then(Value::as_str)
        .ok_or_else(|| anyhow::anyhow!("kb-facets TS: schema has no root `title`"))?;
    out.push('\n');
    out.push_str(&render_interface(root_name, schema)?);
    let keys = schema["properties"]
        .as_object()
        .map(|p| {
            p.keys()
                .map(|k| format!("{k:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default();
    writeln!(out, "\nexport const KB_FACET_KEYS = [{keys}] as const;")?;
    Ok(out)
}

/// Generate (`check=false`) or verify (`check=true`) the generated TS file under `root`.
pub fn run(root: &Path, check: bool) -> Result<()> {
    let schema_path = root.join(SCHEMA_REL);
    let schema: Value = serde_json::from_str(
        &std::fs::read_to_string(&schema_path)
            .map_err(|e| anyhow::anyhow!("kb-facets TS: cannot read {SCHEMA_REL}: {e}"))?,
    )?;
    let rendered = render_kb_facets_ts(&schema)?;
    let out_path = root.join(OUT_REL);
    if check {
        let on_disk = std::fs::read_to_string(&out_path).unwrap_or_default();
        if on_disk != rendered {
            bail!(
                "kb-facets TS drift: {OUT_REL} is stale. Regenerate with \
                 `vox ci config-gui-codegen --kb-facets` and commit."
            );
        }
        println!("kb-facets TS OK: {OUT_REL} matches {SCHEMA_REL}.");
        return Ok(());
    }
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&out_path, &rendered)?;
    println!("kb-facets TS: wrote {OUT_REL}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn repo_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .ancestors()
            .nth(2)
            .expect("repo root")
            .to_path_buf()
    }

    fn committed_schema() -> Value {
        serde_json::from_str(&std::fs::read_to_string(repo_root().join(SCHEMA_REL)).unwrap())
            .unwrap()
    }

    #[test]
    fn renders_small_schema_exactly() {
        let s = json!({
            "title": "Root", "type": "object",
            "properties": {
                "mode": {"description": "Mode.", "anyOf": [{"$ref": "#/definitions/Mode"}, {"type": "null"}]},
                "note": {"type": ["string", "null"]},
                "flag": {"type": ["boolean", "null"]},
                "items": {"type": "array", "items": {"$ref": "#/definitions/Item"}}
            },
            "definitions": {
                "Mode": {"type": "string", "enum": ["a", "b-c"]},
                "Item": {"type": "object", "properties": {"id": {"type": "string"}}, "required": ["id"]}
            }
        });
        let want = format!(
            "{HEADER}\n\nexport interface Item {{\n  id: string;\n}}\n\n\
             export const MODE_VALUES = [\"a\", \"b-c\"] as const;\n\
             export type Mode = (typeof MODE_VALUES)[number];\n\n\
             export interface Root {{\n  /** Mode. */\n  mode?: Mode | null;\n  note?: string | null;\n  flag?: boolean | null;\n  items?: Item[];\n}}\n\n\
             export const KB_FACET_KEYS = [\"mode\", \"note\", \"flag\", \"items\"] as const;\n"
        );
        assert_eq!(render_kb_facets_ts(&s).unwrap(), want);
    }

    #[test]
    fn unsupported_shape_names_the_property() {
        let s = json!({"title": "Root", "type": "object",
            "properties": {"count": {"type": "integer"}}});
        let e = render_kb_facets_ts(&s).unwrap_err().to_string();
        assert!(e.contains("Root.count"), "{e}");
        let s = json!({"title": "Root", "type": "object",
            "properties": {"loose": {"type": "string", "enum": ["x"]}}});
        assert!(
            render_kb_facets_ts(&s)
                .unwrap_err()
                .to_string()
                .contains("Root.loose")
        );
    }

    #[test]
    fn committed_schema_render_is_deterministic_and_ordered() {
        let schema = committed_schema();
        let a = render_kb_facets_ts(&schema).unwrap();
        assert_eq!(a, render_kb_facets_ts(&schema).unwrap());
        let topic = a.find("  topic?:").expect("topic");
        let sens = a.find("  sensitivity?:").expect("sensitivity");
        assert!(topic < sens, "properties must keep schema order");
        assert!(a.contains("export const KB_FACET_KEYS = [\"topic\", \"domain\""));
    }

    #[test]
    fn committed_kb_facets_ts_matches_schema() {
        let root = repo_root();
        if std::env::var("UPDATE_GOLDEN").as_deref() == Ok("1") {
            run(&root, false).unwrap();
        }
        let want = render_kb_facets_ts(&committed_schema()).unwrap();
        let have = std::fs::read_to_string(root.join(OUT_REL)).unwrap_or_default();
        assert!(
            have == want,
            "{OUT_REL} is stale. Regenerate with: \
             UPDATE_GOLDEN=1 cargo nextest run -p vox-cli-ci committed_kb_facets_ts_matches_schema"
        );
    }
}
