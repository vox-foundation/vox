//! Facet backlog (D-03, D-04): the docs excused from specific facet rules until they are
//! curated. Read by the facet lint; written only by the seed/tighten command.

use std::collections::{BTreeMap, BTreeSet};

use serde::{Deserialize, Serialize};

/// Repo-relative path of the committed backlog.
pub const BACKLOG_REL: &str = "contracts/documentation/kb-facet-backlog.v1.yaml";

/// One excused doc: exact repo-relative path (`/` separators) and the rule ids it is excused from.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BacklogRow {
    pub path: String,
    pub rules: Vec<String>,
}

/// The backlog file. Rows are sorted by path, rule ids sorted within a row.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Backlog {
    pub schema_version: u32,
    pub epoch: u32,
    pub epoch_note: String,
    pub docs: Vec<BacklogRow>,
}

fn strictly_sorted(v: &[&str]) -> bool {
    v.windows(2).all(|w| w[0] < w[1])
}

impl Backlog {
    /// Parse and validate. Every problem is reported, joined with newlines.
    pub fn from_yaml_str(s: &str) -> Result<Backlog, String> {
        let b: Backlog = serde_yaml::from_str(s).map_err(|e| e.to_string())?;
        let mut errs: Vec<String> = Vec::new();
        if b.schema_version != 1 {
            errs.push(format!("schema_version {} is not 1", b.schema_version));
        }
        if b.epoch == 0 {
            errs.push("epoch must be >= 1".into());
        }
        if b.epoch_note.trim().is_empty() {
            errs.push("epoch_note must not be blank".into());
        }
        let paths: Vec<&str> = b.docs.iter().map(|r| r.path.as_str()).collect();
        if !strictly_sorted(&paths) {
            errs.push("docs must be sorted by path with no duplicates".into());
        }
        for r in &b.docs {
            if !r.path.starts_with("docs/src/") || !r.path.ends_with(".md") {
                errs.push(format!("{}: path must be docs/src/**/*.md", r.path));
            }
            let rules: Vec<&str> = r.rules.iter().map(String::as_str).collect();
            if rules.is_empty() || rules.iter().any(|x| x.trim().is_empty()) {
                errs.push(format!("{}: rules must be non-empty ids", r.path));
            } else if !strictly_sorted(&rules) {
                errs.push(format!("{}: rules must be sorted and unique", r.path));
            }
        }
        if errs.is_empty() {
            Ok(b)
        } else {
            Err(errs.join("\n"))
        }
    }

    /// Rule ids excused for the exact repo-relative path, or `None` when the doc is not listed.
    #[must_use]
    pub fn rules_for(&self, rel_path: &str) -> Option<&[String]> {
        self.docs
            .binary_search_by(|r| r.path.as_str().cmp(rel_path))
            .ok()
            .map(|i| self.docs[i].rules.as_slice())
    }

    /// Build a backlog from live violations (path -> rule ids). Empty sets are dropped; rows
    /// and rule ids come out sorted (BTree order), so output is deterministic.
    #[must_use]
    pub fn from_violations(
        epoch: u32,
        epoch_note: &str,
        live: &BTreeMap<String, BTreeSet<String>>,
    ) -> Backlog {
        Backlog {
            schema_version: 1,
            epoch,
            epoch_note: epoch_note.to_string(),
            docs: live
                .iter()
                .filter(|(_, r)| !r.is_empty())
                .map(|(p, r)| BacklogRow {
                    path: p.clone(),
                    rules: r.iter().cloned().collect(),
                })
                .collect(),
        }
    }

    /// The committed file text: generated-file header, serde body, trailing newline.
    pub fn to_yaml_string(&self) -> Result<String, String> {
        let body = serde_yaml::to_string(self).map_err(|e| e.to_string())?;
        Ok(format!(
            "# GENERATED by `vox-doc-pipeline --seed-facet-backlog` / `--tighten-facet-backlog`. Never hand-edit.\n\
             # Adding a row or rule id is USER-AUTHORIZED-ONLY: re-seed with a new --epoch-note.\n{}\n",
            body.trim_end()
        ))
    }

    /// Removal-only update (D-04): drop rules that are now clean, rows with no rules left and
    /// rows whose doc is gone. A live (path, rule) pair this backlog does not list is an
    /// addition and returns `Err` with those pairs. Epoch and note are kept.
    pub fn tightened(
        &self,
        live: &BTreeMap<String, BTreeSet<String>>,
    ) -> Result<Backlog, Vec<(String, String)>> {
        let additions: Vec<(String, String)> = live
            .iter()
            .flat_map(|(p, rules)| {
                rules
                    .iter()
                    .filter(move |r| !self.rules_for(p).is_some_and(|l| l.contains(r)))
                    .map(move |r| (p.clone(), r.clone()))
            })
            .collect();
        if !additions.is_empty() {
            return Err(additions);
        }
        let docs = self
            .docs
            .iter()
            .filter_map(|row| {
                let now = live.get(&row.path)?;
                let rules: Vec<String> = row
                    .rules
                    .iter()
                    .filter(|r| now.contains(*r))
                    .cloned()
                    .collect();
                (!rules.is_empty()).then(|| BacklogRow {
                    path: row.path.clone(),
                    rules,
                })
            })
            .collect();
        Ok(Backlog {
            docs,
            ..self.clone()
        })
    }

    /// Gate the head backlog against the base one: without a re-epoch it may only shrink.
    /// `base == None` is bootstrap (no backlog at the base ref yet). `base_docs` is every doc
    /// path that exists in the base tree: a re-epoch may re-seed over those, but never list a
    /// doc that did not exist there (D-03: a new doc is never excused, WR-01).
    #[must_use]
    pub fn tighten_only_violations(
        base: Option<&Backlog>,
        head: &Backlog,
        base_docs: &BTreeSet<String>,
    ) -> Vec<String> {
        let Some(base) = base else {
            return Vec::new();
        };
        if head.epoch < base.epoch {
            return vec![format!(
                "[facet-backlog] epoch went backwards ({} -> {})",
                base.epoch, head.epoch
            )];
        }
        if head.epoch > base.epoch {
            if head.epoch_note.trim().is_empty() || head.epoch_note.trim() == base.epoch_note.trim()
            {
                return vec![format!(
                    "[facet-backlog] epoch {} -> {} needs a new, non-empty epoch_note",
                    base.epoch, head.epoch
                )];
            }
            return head
                .docs
                .iter()
                .filter(|row| !base_docs.contains(&row.path))
                .map(|row| {
                    format!(
                        "[facet-backlog] {}: re-seed lists a doc that does not exist at the base ref (a new or renamed doc is never excused)",
                        row.path
                    )
                })
                .collect();
        }
        head.docs
            .iter()
            .flat_map(|row| {
                row.rules
                    .iter()
                    .filter(|r| !base.rules_for(&row.path).is_some_and(|l| l.contains(r)))
                    .map(|r| {
                        format!(
                            "[facet-backlog] {}: rule {r} added at epoch {} without a re-epoch (USER-AUTHORIZED-ONLY)",
                            row.path, head.epoch
                        )
                    })
                    .collect::<Vec<_>>()
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn y(docs: &str) -> String {
        format!("schema_version: 1\nepoch: 1\nepoch_note: seed\ndocs:{docs}\n")
    }

    #[test]
    fn backlog_accepts_valid_and_looks_up_by_exact_path() {
        let b = Backlog::from_yaml_str(&y(
            "\n  - path: docs/src/a.md\n    rules: [facet-missing-domain, facet-missing-topic]\n  - path: docs/src/b.md\n    rules: [facet-missing-topic]",
        ))
        .unwrap();
        assert_eq!(b.rules_for("docs/src/a.md").unwrap().len(), 2);
        assert!(b.rules_for("docs/src/c.md").is_none());
        assert!(b.rules_for("docs/src/A.md").is_none());
        assert!(Backlog::from_yaml_str(&y(" []")).unwrap().docs.is_empty());
    }

    #[test]
    fn backlog_rejects_every_malformed_shape() {
        let bad = [
            "schema_version: 1\nepoch: 1\nepoch_note: n\ndocs: []\nextra: 1\n".to_string(),
            "schema_version: 2\nepoch: 1\nepoch_note: n\ndocs: []\n".to_string(),
            "schema_version: 1\nepoch: 0\nepoch_note: n\ndocs: []\n".to_string(),
            "schema_version: 1\nepoch: 1\nepoch_note: '  '\ndocs: []\n".to_string(),
            y("\n  - path: docs/src/b.md\n    rules: [x]\n  - path: docs/src/a.md\n    rules: [x]"),
            y("\n  - path: docs/src/a.md\n    rules: [x]\n  - path: docs/src/a.md\n    rules: [x]"),
            y("\n  - path: docs/src/a.md\n    rules: []"),
            y("\n  - path: docs/src/a.md\n    rules: [b, a]"),
            y("\n  - path: docs/src/a.md\n    rules: [a, a]"),
            y("\n  - path: other/a.md\n    rules: [a]"),
            y("\n  - path: docs/src/a.mdx\n    rules: [a]"),
        ];
        for s in &bad {
            assert!(Backlog::from_yaml_str(s).is_err(), "accepted: {s}");
        }
    }

    fn live(rows: &[(&str, &[&str])]) -> BTreeMap<String, BTreeSet<String>> {
        rows.iter()
            .map(|(p, r)| {
                (
                    (*p).to_string(),
                    r.iter().map(|x| (*x).to_string()).collect(),
                )
            })
            .collect()
    }

    #[test]
    fn from_violations_is_sorted_roundtrips_and_deterministic() {
        let l = live(&[
            ("docs/src/b.md", &["z", "a"]),
            ("docs/src/a.md", &["m"]),
            ("docs/src/e.md", &[]),
        ]);
        let b = Backlog::from_violations(1, "n", &l);
        assert_eq!(b.docs.len(), 2);
        assert_eq!(b.docs[0].path, "docs/src/a.md");
        assert_eq!(b.docs[1].rules, ["a", "z"]);
        let t = b.to_yaml_string().unwrap();
        assert!(t.starts_with("# GENERATED"));
        assert!(t.contains("USER-AUTHORIZED-ONLY"));
        assert_eq!(Backlog::from_yaml_str(&t).unwrap(), b);
        assert_eq!(
            t,
            Backlog::from_violations(1, "n", &l)
                .to_yaml_string()
                .unwrap()
        );
    }

    fn bl(epoch: u32, note: &str, rows: &[(&str, &[&str])]) -> Backlog {
        Backlog::from_violations(epoch, note, &live(rows))
    }

    #[test]
    fn tighten_is_removal_only() {
        let b = bl(
            3,
            "n",
            &[
                ("docs/src/a.md", &["r1", "r2"]),
                ("docs/src/b.md", &["r1"]),
                ("docs/src/gone.md", &["r1"]),
            ],
        );
        // r2 fixed in a, b fully clean (absent from live), gone.md deleted (absent from live)
        let t = b.tightened(&live(&[("docs/src/a.md", &["r1"])])).unwrap();
        assert_eq!(t.docs, bl(3, "n", &[("docs/src/a.md", &["r1"])]).docs);
        assert_eq!((t.epoch, t.epoch_note.as_str()), (3, "n"));
        // a new rule on a listed doc, and a new doc, are additions
        let add = b
            .tightened(&live(&[
                ("docs/src/a.md", &["r1", "r9"]),
                ("docs/src/c.md", &["r1"]),
            ]))
            .unwrap_err();
        assert_eq!(
            add,
            [
                ("docs/src/a.md".to_string(), "r9".to_string()),
                ("docs/src/c.md".to_string(), "r1".to_string())
            ]
        );
    }

    #[test]
    fn gate_rejects_same_epoch_addition() {
        let base = bl(1, "seed", &[("docs/src/a.md", &["r1"])]);
        let tree: BTreeSet<String> = ["docs/src/a.md", "docs/src/b.md"]
            .iter()
            .map(|s| (*s).to_string())
            .collect();
        let v = |h: &Backlog| Backlog::tighten_only_violations(Some(&base), h, &tree);
        assert!(Backlog::tighten_only_violations(None, &base, &BTreeSet::new()).is_empty());
        assert!(v(&base).is_empty());
        assert!(v(&bl(1, "seed", &[])).is_empty());
        let new_row = v(&bl(
            1,
            "seed",
            &[("docs/src/a.md", &["r1"]), ("docs/src/b.md", &["r1", "r2"])],
        ));
        assert_eq!(new_row.len(), 2, "{new_row:?}");
        assert!(new_row[0].contains("docs/src/b.md"));
        assert_eq!(
            v(&bl(1, "seed", &[("docs/src/a.md", &["r1", "r2"])])).len(),
            1
        );
        assert_eq!(v(&bl(0, "seed", &[])).len(), 1);
        let big = [
            ("docs/src/a.md", &["r1"][..]),
            ("docs/src/b.md", &["r1"][..]),
        ];
        assert!(v(&bl(2, "re-seed after import", &big)).is_empty());
        assert_eq!(v(&bl(2, "seed", &big)).len(), 1, "unchanged note");
        assert_eq!(v(&bl(2, "  ", &big)).len(), 1, "blank note");
    }

    /// WR-01: a re-epoch re-seeds over existing docs but cannot excuse a doc that is new.
    #[test]
    fn re_epoch_rejects_rows_for_docs_absent_from_the_base_tree() {
        let base = bl(1, "seed", &[("docs/src/a.md", &["r1"])]);
        let tree: BTreeSet<String> = std::iter::once("docs/src/a.md".to_string()).collect();
        let v = |h: &Backlog| Backlog::tighten_only_violations(Some(&base), h, &tree);
        // legitimate re-seed: existing doc gains a rule at a new epoch
        assert!(v(&bl(2, "reseed", &[("docs/src/a.md", &["r1", "r2"])])).is_empty());
        // seed-your-own-new-doc: a brand-new path at a re-epoch is rejected and named
        let own = v(&bl(
            2,
            "reseed",
            &[("docs/src/a.md", &["r1"]), ("docs/src/new.md", &["r1"])],
        ));
        assert_eq!(own.len(), 1, "{own:?}");
        assert!(own[0].contains("docs/src/new.md"), "{own:?}");
        // an empty base tree (listing failed to find docs) fails closed on every row
        let none = Backlog::tighten_only_violations(
            Some(&base),
            &bl(2, "reseed", &[("docs/src/a.md", &["r1"])]),
            &BTreeSet::new(),
        );
        assert_eq!(none.len(), 1);
    }
}
