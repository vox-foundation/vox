export function normalizeTrustTier(raw: unknown): KbSearchResultItem['trustTier'] {
  if (raw === 'canonical_doc' || raw === 'quarantined_web' || raw === 'legacy') return raw;
  return 'verified';
}

export function resolveDocStatusInfo(markdown?: string) {
  if (!markdown) return null;
  const match = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return null;
  const statusMatch = match[1].match(/^status:\s*["']?([^"'\r\n]+)["']?/m);
  if (!statusMatch) return null;
  const status = statusMatch[1].trim().toLowerCase();
  switch (status) {
    case 'research':
      return {
        label: 'Internals — research note',
        description: 'Investigation or findings, not a description of shipped behaviour.',
        tone: 'border-(--color-status-warn)/40 bg-(--color-status-warn)/10 text-(--color-status-warn)',
        trustBadge: 'Canonical Research',
      };
    case 'roadmap':
      return {
        label: 'Internals — roadmap',
        description: 'Describes planned work that may not match the current code.',
        tone: 'border-brass/40 bg-brass/10 text-brass',
        trustBadge: 'Roadmap Plan',
      };
    case 'deprecated':
      return {
        label: 'Deprecated',
        description: 'Kept for migration notes only; do not build on this.',
        tone: 'border-(--color-status-error)/40 bg-(--color-status-error)/10 text-(--color-status-error)',
        trustBadge: 'Deprecated',
      };
    case 'legacy':
      return {
        label: 'Legacy',
        description: 'Still present, but not the recommended path.',
        tone: 'border-(--color-status-pass)/40 bg-(--color-status-pass)/10 text-(--color-status-pass)',
        trustBadge: 'Legacy',
      };
    default:
      return null;
  }
}

export function mapKbSearchHits(hits: Array<Record<string, unknown>>): KbSearchResultItem[] {
  const seen = new Set<string>();
  const mapped: KbSearchResultItem[] = [];
  for (const h of hits) {
    const docPath = typeof h.doc_path === 'string' ? h.doc_path : '';
    if (!docPath || seen.has(docPath)) continue;
    seen.add(docPath);
    mapped.push({
      path: docPath,
      title: typeof h.title === 'string' && h.title ? h.title : docPath.split('/').pop() ?? docPath,
      topic: typeof h.topic === 'string' ? h.topic : 'doc-governance',
      domain: typeof h.domain === 'string' ? h.domain : 'documentation',
      trustTier: normalizeTrustTier(h.trust_tier),
      rrfScore: typeof h.score === 'number' ? h.score : 0,
    });
  }
  return mapped;
}

export function mapInboxFindings(findings: Array<Record<string, unknown>>): KbFindingItem[] {
  return findings.map((f) => ({
    id: String(f.id ?? ''),
    claim: String(f.claim ?? ''),
    citationAnchor: String(f.citation_anchor ?? f.citationAnchor ?? ''),
    trustTier:
      f.trust_tier === 'quarantined_web' ||
      f.trust_tier === 'verified_finding' ||
      f.trust_tier === 'rejected'
        ? f.trust_tier
        : 'candidate',
    confidence: typeof f.confidence === 'number' ? f.confidence : 0,
    topic: String(f.topic ?? 'general'),
  }));
}

export function splitDiffColumns(
  unifiedDiff: string,
  patchedMarkdown: string,
): { removed: string[]; added: string[] } {
  const removed: string[] = [];
  const added: string[] = [];
  for (const line of unifiedDiff.split('\n')) {
    if (line.startsWith('---') || line.startsWith('+++') || line.startsWith('@@')) continue;
    if (line.startsWith('-')) removed.push(line.slice(1));
    else if (line.startsWith('+')) added.push(line.slice(1));
  }
  if (removed.length === 0 && added.length === 0 && patchedMarkdown.trim().length > 0) {
    return {
      removed: ['(auto-fence / AST region refresh)'],
      added: patchedMarkdown.split('\n').slice(0, 24),
    };
  }
  return { removed, added };
}
