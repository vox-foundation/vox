//! Shrink-only ratchet on legacy ```` ```mermaid ```` fences (VoxDiagram Phase 87, DOCS-01).
//!
//! Counts `mermaid` fences per file under `docs/src` (`archive/` excluded) with
//! `vox_diagram::fence::extract`, so prose mentions and fences nested in longer example fences
//! never count while tilde and list-nested fences do. Doc lint compares the live counts with
//! `contracts/documentation/legacy-mermaid-baseline.v1.yaml` on every run, scoped or not.
//! The baseline only shrinks: `--seed-mermaid-baseline` writes it from the tree and
//! `--tighten-mermaid-baseline` lowers it; raising a count is USER-AUTHORIZED-ONLY.

use std::collections::BTreeMap;
use std::path::Path;

use serde::{Deserialize, Serialize};
use vox_diagram::fence;

use super::diagrams::near_miss_fences;
use super::lint::gather_md_files;
use super::types::{LintError, LintKind, MermaidIssue};

/// Repo-relative path of the baseline contract.
pub const MERMAID_BASELINE_REL: &str = "contracts/documentation/legacy-mermaid-baseline.v1.yaml";

const HEADER: &str = "\
# GENERATED by cargo run -p vox-doc-pipeline -- --seed-mermaid-baseline. Never hand-edit.
# Shrink-only per-file count of legacy mermaid fences under docs/src (archive/ excluded), VoxDiagram Phase 87.
# Lower it with --tighten-mermaid-baseline; raising a count or adding a file is USER-AUTHORIZED-ONLY.
";

pub(crate) const MERMAID_HEAL: &str = "\
HEAL: the legacy-Mermaid baseline only shrinks. Legal moves:
  1. Author new diagrams as ```vox-diagram, not ```mermaid.
  2. After migrating a diagram away, run
       cargo run -p vox-doc-pipeline -- --tighten-mermaid-baseline
  3. Raising a count or adding a file is USER-AUTHORIZED-ONLY. Propose it in the PR description and stop.
Never hand-edit contracts/documentation/legacy-mermaid-baseline.v1.yaml.";

#[derive(Serialize, Deserialize, Debug, Default, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
struct Baseline {
    schema_version: u32,
    files: BTreeMap<String, usize>,
}

fn parse(text: &str) -> Result<Baseline, String> {
    let b: Baseline = serde_yaml::from_str(text).map_err(|e| e.to_string())?;
    if b.schema_version != 1 {
        return Err(format!("unsupported schema_version {}", b.schema_version));
    }
    Ok(b)
}

fn render(b: &Baseline) -> Result<String, String> {
    let body = serde_yaml::to_string(b).map_err(|e| e.to_string())?;
    Ok(format!("{HEADER}{body}"))
}

/// `None` when the file is absent; a present but invalid file is an error.
fn load(root: &Path) -> Result<Option<Baseline>, String> {
    let p = root.join(MERMAID_BASELINE_REL);
    if !p.exists() {
        return Ok(None);
    }
    let text = vox_bounded_fs::read_utf8_path_capped(&p).map_err(|e| e.to_string())?;
    parse(&text).map(Some)
}

/// `(repo-relative path, text)` of every non-archive doc under `docs/src` mentioning `mermaid`.
fn docs(root: &Path) -> Result<Vec<(String, String)>, MermaidIssue> {
    let mut files = Vec::new();
    gather_md_files(&root.join("docs/src"), &mut files);
    files.sort();
    let mut out = Vec::new();
    for f in files {
        let rel = f
            .strip_prefix(root)
            .unwrap_or(&f)
            .to_string_lossy()
            .replace('\\', "/");
        if rel.starts_with("docs/src/archive/") {
            continue;
        }
        let text =
            vox_bounded_fs::read_utf8_path_capped(&f).map_err(|e| MermaidIssue::Unreadable {
                path: rel.clone(),
                error: e.to_string(),
            })?;
        if text.contains("mermaid") {
            out.push((rel, text));
        }
    }
    Ok(out)
}

/// Path -> 1-based opener lines of its `mermaid` fences (paths with none omitted).
fn counts(docs: &[(String, String)]) -> BTreeMap<String, Vec<usize>> {
    docs.iter()
        .filter_map(|(path, text)| {
            let lines: Vec<usize> = fence::extract(text, "mermaid")
                .iter()
                .map(|f| f.open_line as usize)
                .collect();
            (!lines.is_empty()).then(|| (path.clone(), lines))
        })
        .collect()
}

fn push(errors: &mut Vec<LintError>, root: &Path, path: &str, line: usize, issue: MermaidIssue) {
    errors.push(LintError {
        file: root.join(path),
        line,
        kind: LintKind::LegacyMermaid(issue),
    });
}

/// Hold the whole `docs/src` tree to the baseline (missing baseline admits nothing).
pub(crate) fn lint(root: &Path, errors: &mut Vec<LintError>) {
    let unreadable = |path: &str, error: String| MermaidIssue::Unreadable {
        path: path.to_string(),
        error,
    };
    let baseline = match load(root) {
        Ok(b) => b.unwrap_or_default(),
        Err(e) => {
            let i = unreadable(MERMAID_BASELINE_REL, e);
            push(errors, root, MERMAID_BASELINE_REL, 0, i);
            return;
        }
    };
    let docs = match docs(root) {
        Ok(d) => d,
        Err(i) => {
            let path = match &i {
                MermaidIssue::Unreadable { path, .. } => path.clone(),
                _ => String::new(),
            };
            push(errors, root, &path, 0, i);
            return;
        }
    };
    let live = counts(&docs);
    let paths: std::collections::BTreeSet<&String> =
        live.keys().chain(baseline.files.keys()).collect();
    for path in paths {
        let allowed = baseline.files.get(path).copied().unwrap_or(0);
        let lines = live.get(path).map_or(&[][..], Vec::as_slice);
        let count = lines.len();
        if count > allowed {
            let i = MermaidIssue::Growth { count, allowed };
            push(errors, root, path, lines[allowed], i);
        } else if count < allowed {
            push(
                errors,
                root,
                path,
                0,
                MermaidIssue::Stale { count, allowed },
            );
        }
    }
    for (path, text) in &docs {
        for (line, info) in near_miss_fences(text, "mermaid") {
            push(errors, root, path, line, MermaidIssue::InfoString { info });
        }
    }
}

impl MermaidIssue {
    pub(crate) fn rule_id(&self) -> &'static str {
        match self {
            Self::Growth { .. } => "legacy-mermaid-growth",
            Self::Stale { .. } => "legacy-mermaid-stale",
            Self::InfoString { .. } => "legacy-mermaid-info",
            Self::Unreadable { .. } => "legacy-mermaid-unreadable",
        }
    }

    /// Everything but a stale baseline entry blocks.
    pub(crate) fn is_hard(&self) -> bool {
        !matches!(self, Self::Stale { .. })
    }

    pub(crate) fn workflow(&self) -> &'static str {
        match self {
            Self::Growth { .. } => {
                "author new diagrams as ```vox-diagram; raising the baseline is USER-AUTHORIZED-ONLY"
            }
            Self::Stale { .. } => "run cargo run -p vox-doc-pipeline -- --tighten-mermaid-baseline",
            Self::InfoString { .. } => {
                "use exactly ```mermaid, or migrate the fence to ```vox-diagram"
            }
            Self::Unreadable { .. } => {
                "fix or restore the file; the baseline is written only by --seed-mermaid-baseline (USER-AUTHORIZED-ONLY)"
            }
        }
    }

    pub(crate) fn message(&self) -> String {
        match self {
            Self::Growth { count, allowed } => format!(
                "{count} ```mermaid fence(s), the legacy-Mermaid baseline allows {allowed}; author new diagrams as ```vox-diagram"
            ),
            Self::Stale { count, allowed } => format!(
                "{count} ```mermaid fence(s) but the baseline allows {allowed}; run --tighten-mermaid-baseline"
            ),
            Self::InfoString { info } => format!(
                "info string {info:?} is not exactly `mermaid`, so the fence would escape the count"
            ),
            Self::Unreadable { path, error } => format!("cannot read or validate {path}: {error}"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn n(text: &str) -> usize {
        counts(&[("a.md".to_string(), text.to_string())])
            .get("a.md")
            .map_or(0, Vec::len)
    }

    #[test]
    fn counts_are_fence_aware() {
        assert_eq!(n("````markdown\n```mermaid\ngraph TD\n```\n````\n"), 0);
        assert_eq!(n("Never add ```mermaid fences.\n"), 0);
        assert_eq!(n("~~~mermaid\ngraph TD\n~~~\n"), 1);
        assert_eq!(n("- item\n\n  ```mermaid\n  graph TD\n  ```\n"), 1);
        let near = "```mermaid,foo\ngraph TD\n```\n";
        assert_eq!(n(near), 0);
        assert_eq!(
            near_miss_fences(near, "mermaid"),
            [(1, "mermaid,foo".to_string())]
        );
        assert_eq!(n("```mermaid\na\n```\n\n```mermaid\nb\n```\n"), 2);
    }

    #[test]
    fn parse_rejects_unknown_keys_and_other_schema_versions() {
        assert!(parse("schema_version: 2\nfiles: {}\n").is_err());
        assert!(parse("schema_version: 1\nfiles: {}\nextra: 1\n").is_err());
        assert!(parse("schema_version: 1\nfiles: {}\n").is_ok());
    }
}

