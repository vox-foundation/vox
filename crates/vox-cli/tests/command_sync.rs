//! Integration tests for `vox ci command-sync` (GEN-01, GEN-02, GEN-03).

use std::path::PathBuf;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("crates dir")
        .parent()
        .expect("repo root")
        .to_path_buf()
}

#[test]
fn test_command_sync_clean_verification() {
    let root = repo_root();
    // command-sync verify should pass on the live repo without modifying files
    let res = vox_cli::commands::ci::command_sync::verify(&root);
    assert!(
        res.is_ok(),
        "command-sync::verify failed on repository: {:?}",
        res.err()
    );
}

#[test]
fn test_generated_docs_exist_and_non_empty() {
    let root = repo_root();
    let expected = [
        "docs/src/reference/cli-command-surface.generated.md",
        "docs/src/reference/mens-train-defaults.generated.md",
        "docs/src/reference/env-vars.generated.md",
        "docs/src/reference/config-keys.generated.md",
        "docs/src/reference/mcp-tools.generated.md",
    ];

    for rel in expected {
        let p = root.join(rel);
        assert!(p.is_file(), "Generated doc {} does not exist", rel);
        let content = std::fs::read_to_string(&p).expect("read generated doc");
        assert!(
            content.contains("AUTO-GENERATED FILE. DO NOT EDIT THIS FILE MANUALLY!"),
            "Generated doc {} missing warning banner",
            rel
        );
        assert!(
            content.contains("Intended readers:")
                || rel.contains("cli-command")
                || rel.contains("mens-train"),
            "Generated doc {} missing intended readers",
            rel
        );
    }
}

#[test]
fn test_command_sync_dead_path_fails_gracefully() {
    let tmp = tempfile::tempdir().expect("tempdir");
    // Running against an empty tempdir (where contracts are missing) returns Err, doesn't panic
    let res = vox_cli::commands::ci::command_sync::run(tmp.path(), false);
    assert!(
        res.is_err(),
        "command_sync should fail gracefully when contracts are missing"
    );
}
