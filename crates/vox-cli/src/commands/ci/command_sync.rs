//! `vox ci command-sync` — regenerate or verify generated CLI/reference docs.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result, anyhow};
use serde::Deserialize;

use crate::command_registry_model::RegistryFile;
use vox_bounded_fs::read_utf8_path_capped;

const REGISTRY_REL: &str = "contracts/cli/command-registry.yaml";

const GENERATED_REL: &str = "docs/src/reference/cli-command-surface.generated.md";
const GENERATED_MENS_DEFAULTS_REL: &str = "docs/src/reference/mens-train-defaults.generated.md";

const ENV_VARS_REL: &str = "contracts/config/env-vars.v1.yaml";
const GENERATED_ENV_VARS_REL: &str = "docs/src/reference/env-vars.generated.md";

const CONFIG_REGISTRY_REL: &str = "contracts/config/registry.v1.yaml";
const GENERATED_CONFIG_KEYS_REL: &str = "docs/src/reference/config-keys.generated.md";

const MCP_REGISTRY_REL: &str = "contracts/mcp/tool-registry.canonical.yaml";
const GENERATED_MCP_TOOLS_REL: &str = "docs/src/reference/mcp-tools.generated.md";

fn normalize_lf(s: &str) -> String {
    s.replace("\r\n", "\n").replace('\r', "\n")
}

const WARNING_BLOCK: &str = r#"<!--
  ========================================================================
  🛑 🛑 🛑 AUTO-GENERATED FILE. DO NOT EDIT THIS FILE MANUALLY! 🛑 🛑 🛑
  ========================================================================
  
  ATTENTION AI AGENTS, LLMs, AND BOTS:
  This file is automatically generated by `vox ci command-sync`.
  Any manual edits you make here WILL BE OVERWRITTEN AND LOST.
  
  DO NOT USE `replace_file_content` or similar tools on this file.
  ========================================================================
-->"#;

fn render_generated_md(reg: &RegistryFile) -> String {
    let mut out = String::new();
    // Docs lint (`vox-doc-pipeline`) requires YAML frontmatter on every `.md` under `docs/src/`.
    out.push_str("---\n");
    out.push_str("title: \"CLI command surface (generated)\"\n");
    out.push_str("description: \"Auto-generated table of vox command paths and metadata; CLI rows are generated from contracts/operations/catalog.v1.yaml into command-registry.yaml — use vox ci operations-sync --target cli --write then vox ci command-sync --write.\"\n");
    out.push_str("category: \"Language Reference\"\n");
    out.push_str("---\n\n");
    out.push_str(WARNING_BLOCK);
    out.push_str("\n\n# CLI command surface (generated)\n\n");
    out.push_str("Machine-derived from [`contracts/cli/command-registry.yaml`](../../../contracts/cli/command-registry.yaml) (itself projected from [`contracts/operations/catalog.v1.yaml`](../../../contracts/operations/catalog.v1.yaml)).\n\n");
    out.push_str(&format!(
        "**schema_version:** `{}` · **vox-cli operations:** {}\n\n",
        reg.schema_version,
        reg.operations
            .iter()
            .filter(|o| o.surface == "vox-cli")
            .count()
    ));
    out.push_str("| Path | Status | Feature gate | Latin ns | Product lane | Catalog group |\n");
    out.push_str("|------|--------|--------------|----------|--------------|----------------|\n");
    let mut ops: Vec<_> = reg
        .operations
        .iter()
        .filter(|o| o.surface == "vox-cli")
        .collect();
    ops.sort_by(|a, b| a.path.cmp(&b.path));
    for op in ops {
        let path = op.path.join(" ");
        let gate = op.feature_gate.as_deref().unwrap_or("—");
        let latin = op.latin_ns.as_deref().unwrap_or("—");
        let lane = op.product_lane.as_deref().unwrap_or("—");
        let cg = op.catalog_group.as_deref().unwrap_or("—");
        out.push_str(&format!(
            "| `vox {}` | {} | {} | {} | {} | {} |\n",
            path, op.status, gate, latin, lane, cg
        ));
    }
    out
}

fn render_mens_train_defaults_md(default_base_model: &str) -> String {
    let mut out = String::new();
    out.push_str("---\n");
    out.push_str("title: \"Mens train defaults (generated)\"\n");
    out.push_str("description: \"Auto-generated defaults snapshot for vox mens train from Rust constants and canonical command defaults.\"\n");
    out.push_str("category: \"Language Reference\"\n");
    out.push_str("---\n\n");
    out.push_str(WARNING_BLOCK);
    out.push_str("\n\n# Mens train defaults (generated)\n\n");
    out.push_str(
        "This snapshot is generated from code-level constants and canonical CLI defaults.\n\n",
    );
    out.push_str("| Setting | Value | Source |\n");
    out.push_str("|---|---|---|\n");
    out.push_str(&format!(
        "| Default model id | `{}` | `contracts/mens/training-presets.v1.yaml::default_base_model` |\n",
        default_base_model
    ));
    out.push_str(&format!(
        "| Canonical train data dir | `{}` | `vox_corpus::training::CANONICAL_TRAIN_DATA_DIR` |\n",
        vox_corpus::training::CANONICAL_TRAIN_DATA_DIR
    ));
    out.push_str("| Canonical backend | `qlora` | `vox mens train` command defaults |\n");
    out.push_str("| Canonical tokenizer | `hf` | `vox mens train` command defaults |\n");
    out.push_str(
        "| Canonical output dir | `mens/runs/latest` | `vox mens train` command defaults |\n",
    );
    out
}

fn write_or_verify_generated_file(
    repo_root: &Path,
    rel_path: &str,
    rendered: &str,
    write: bool,
) -> Result<()> {
    let out_path = repo_root.join(rel_path);
    if write {
        fs::write(&out_path, normalize_lf(rendered))
            .with_context(|| format!("write {}", out_path.display()))?;
        println!("Wrote {}", out_path.display());
        return Ok(());
    }
    if !out_path.is_file() {
        return Err(anyhow!(
            "missing {}; run `vox ci command-sync --write`",
            out_path.display()
        ));
    }
    let existing =
        read_utf8_path_capped(&out_path).with_context(|| format!("read {}", out_path.display()))?;
    if normalize_lf(&existing) != normalize_lf(rendered) {
        return Err(anyhow!(
            "{} is stale; run `vox ci command-sync --write` from the repo root",
            out_path.display()
        ));
    }
    Ok(())
}

#[derive(Deserialize, Debug)]
struct EnvVarsFile {
    #[serde(default)]
    _version: u32,
    variables: Vec<EnvVarEntry>,
}

#[derive(Deserialize, Debug, Clone)]
struct EnvVarEntry {
    name: String,
    owner_crate: String,
    kind: String,
    #[serde(default)]
    required: bool,
    #[serde(default)]
    introduced_in: String,
    #[serde(default)]
    description: String,
}

#[derive(Deserialize, Debug)]
struct ConfigRegistryFile {
    #[serde(default)]
    _schema_version: String,
    knobs: Vec<ConfigKnobEntry>,
}

#[derive(Deserialize, Debug, Clone)]
struct ConfigKnobEntry {
    name: String,
    #[serde(default)]
    env_var: Option<String>,
    #[serde(default)]
    description: String,
    owner_crate: String,
    #[serde(default)]
    status: String,
    #[serde(default)]
    default_value: Option<String>,
    #[serde(default)]
    _since: Option<String>,
}

#[derive(Deserialize, Debug)]
struct McpToolRegistryFile {
    #[serde(default)]
    _version: u32,
    tools: Vec<McpToolEntry>,
}

#[derive(Deserialize, Debug, Clone)]
struct McpToolEntry {
    name: String,
    description: String,
    #[serde(default)]
    product_lane: String,
    #[serde(default)]
    http_read_role_eligible: bool,
    #[serde(default)]
    tier: String,
}

fn escape_table_cell(s: &str) -> String {
    s.replace('\r', "")
        .replace('\n', " ")
        .replace('|', "\\|")
        .trim()
        .to_string()
}

fn render_env_vars_md(vars_file: &EnvVarsFile) -> String {
    let mut out = String::new();
    out.push_str("---\n");
    out.push_str("title: \"Environment variables (generated)\"\n");
    out.push_str("description: \"Machine-derived reference for all environment variables declared across Vox workspace crates.\"\n");
    out.push_str("category: \"Language Reference\"\n");
    out.push_str("status: current\n");
    out.push_str("---\n\n");
    out.push_str(WARNING_BLOCK);
    out.push_str("\n\n# Environment variables (generated)\n\n");
    out.push_str("**Intended readers:** Developers configuring Vox CLI, runtime developers, and operators deploying Vox services.\n\n");
    out.push_str("Machine-derived from [`contracts/config/env-vars.v1.yaml`](../../../contracts/config/env-vars.v1.yaml).\n\n");
    out.push_str(&format!(
        "**Total variables:** {}\n\n",
        vars_file.variables.len()
    ));
    out.push_str("| Variable | Owner Crate | Type | Required | Introduced | Description |\n");
    out.push_str("|---|---|---|---|---|---|\n");

    let mut vars = vars_file.variables.clone();
    vars.sort_by(|a, b| a.name.cmp(&b.name));
    for v in vars {
        let req = if v.required { "Yes" } else { "No" };
        let desc = escape_table_cell(&v.description);
        out.push_str(&format!(
            "| `{}` | `{}` | {} | {} | {} | {} |\n",
            v.name, v.owner_crate, v.kind, req, v.introduced_in, desc
        ));
    }
    out
}

fn render_config_keys_md(cfg_file: &ConfigRegistryFile) -> String {
    let mut out = String::new();
    out.push_str("---\n");
    out.push_str("title: \"Configuration keys (generated)\"\n");
    out.push_str("description: \"Machine-derived reference for runtime configuration knobs, budgets, and operational defaults.\"\n");
    out.push_str("category: \"Language Reference\"\n");
    out.push_str("status: current\n");
    out.push_str("---\n\n");
    out.push_str(WARNING_BLOCK);
    out.push_str("\n\n# Configuration keys (generated)\n\n");
    out.push_str("**Intended readers:** Operators, system administrators, and developers tuning Vox runtime knobs and pipeline limits.\n\n");
    out.push_str("Machine-derived from [`contracts/config/registry.v1.yaml`](../../../contracts/config/registry.v1.yaml).\n\n");
    out.push_str(&format!("**Total knobs:** {}\n\n", cfg_file.knobs.len()));
    out.push_str("| Key | Environment Variable | Owner Crate | Status | Default | Description |\n");
    out.push_str("|---|---|---|---|---|---|\n");

    let mut knobs = cfg_file.knobs.clone();
    knobs.sort_by(|a, b| a.name.cmp(&b.name));
    for k in knobs {
        let env_str = k
            .env_var
            .as_deref()
            .map(|e| format!("`{}`", e))
            .unwrap_or_else(|| "—".to_string());
        let def_str = k
            .default_value
            .as_deref()
            .map(|d| format!("`{}`", d))
            .unwrap_or_else(|| "—".to_string());
        let desc = escape_table_cell(&k.description);
        out.push_str(&format!(
            "| `{}` | {} | `{}` | {} | {} | {} |\n",
            k.name, env_str, k.owner_crate, k.status, def_str, desc
        ));
    }
    out
}

