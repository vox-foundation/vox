#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct IntrospectedColumn {
    pub name: String,
    pub data_type: String,
    pub nullable: bool,
    pub is_primary_key: bool,
    pub default_expr: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct IntrospectedTable {
    pub name: String,
    pub columns: Vec<IntrospectedColumn>,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct IntrospectedSchema {
    pub backend: String,
    pub tables: Vec<IntrospectedTable>,
}

impl IntrospectedSchema {
    /// Render the live schema as Vox `table(extern, source: …, pk: …)` declarations
    /// (`vox db introspect --emit vox`).
    ///
    /// Column types use [`crate::type_map::sql_type_to_vox`], the inverse of the mapping
    /// `vox db verify` checks against, so canonical columns round-trip. Nullable non-key
    /// columns become `Option[T]`; unmappable SQL types become `str` with a
    /// `// vox: unmapped sql type <t>` comment (verify will report those as drift).
    pub fn to_vox_source(&self) -> String {
        use std::fmt::Write as _;
        let backend = match self.backend.as_str() {
            #[cfg(feature = "postgres")]
            "postgres" => crate::BackendKind::Postgres,
            #[cfg(feature = "mysql")]
            "mysql" => crate::BackendKind::MySql,
            _ => crate::BackendKind::Libsql,
        };
        let mut out = format!(
            "// Generated by `vox db introspect --emit vox` from a live {} schema.\n\
             // If another tool owns this schema, set `[db] schema_owner = \"external\"` in Vox.toml.\n",
            self.backend
        );
        for table in &self.tables {
            let pks: Vec<&str> = table
                .columns
                .iter()
                .filter(|c| c.is_primary_key)
                .map(|c| c.name.as_str())
                .collect();
            out.push('\n');
            if pks.len() > 1 {
                let _ = writeln!(
                    out,
                    "// vox: composite primary key ({}); only `{}` is declared as pk",
                    pks.join(", "),
                    pks[0]
                );
            }
            let source = table.name.replace('\\', "\\\\").replace('"', "\\\"");
            let pk = pks
                .first()
                .map(|p| format!(", pk: {p}"))
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "table(extern, source: \"{source}\"{pk}) {} {{",
                pascal_case(&table.name)
            );
            for c in &table.columns {
                let mapped = crate::type_map::sql_type_to_vox(backend, &c.data_type);
                let base = mapped.unwrap_or("str");
                let ty = if c.nullable && !c.is_primary_key {
                    format!("Option[{base}]")
                } else {
                    base.to_string()
                };
                let _ = write!(out, "    {}: {ty}", c.name);
                if mapped.is_none() {
                    let _ = write!(out, " // vox: unmapped sql type {}", c.data_type);
                }
                out.push('\n');
            }
            out.push_str("}\n");
        }
        out
    }
}

/// `blog_posts` -> `BlogPosts`; a leading digit gets a `T` prefix (`3d` -> `T3d`).
fn pascal_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 1);
    let mut upper = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            if upper {
                out.push(ch.to_ascii_uppercase());
            } else {
                out.push(ch);
            }
            upper = false;
        } else {
            upper = true;
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'T');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str, nullable: bool, pk: bool) -> IntrospectedColumn {
        IntrospectedColumn {
            name: name.to_string(),
            data_type: ty.to_string(),
            nullable,
            is_primary_key: pk,
            default_expr: None,
        }
    }

    #[test]
    fn to_vox_source_renders_extern_table_decls() {
        let schema = IntrospectedSchema {
            backend: "sqlite".to_string(),
            tables: vec![IntrospectedTable {
                name: "blog_posts".to_string(),
                columns: vec![
                    // SQLite reports INTEGER PRIMARY KEY as nullable; a pk is never Option.
                    col("post_id", "INTEGER", true, true),
                    col("title", "TEXT", false, false),
                    col("score", "REAL", true, false),
                    col("slug", "VARCHAR(20)", false, false),
                ],
            }],
        };
        let src = schema.to_vox_source();
        assert!(
            src.contains("table(extern, source: \"blog_posts\", pk: post_id) BlogPosts {"),
            "{src}"
        );
        assert!(src.contains("    post_id: int\n"), "{src}");
        assert!(src.contains("    title: str\n"), "{src}");
        assert!(src.contains("    score: Option[float]\n"), "{src}");
        assert!(
            src.contains("    slug: str // vox: unmapped sql type VARCHAR(20)\n"),
            "{src}"
        );
    }

    #[test]
    fn to_vox_source_pascal_cases_and_prefixes_digit_names() {
        let schema = IntrospectedSchema {
            backend: "sqlite".to_string(),
            tables: vec![IntrospectedTable {
                name: "3d_models".to_string(),
                columns: vec![col("id", "INTEGER", false, true)],
            }],
        };
        let src = schema.to_vox_source();
        assert!(
            src.contains("table(extern, source: \"3d_models\", pk: id) T3dModels {"),
            "{src}"
        );
    }

    #[test]
    fn to_vox_source_is_empty_safe() {
        let schema = IntrospectedSchema {
            backend: "sqlite".to_string(),
            tables: vec![],
        };
        assert!(!schema.to_vox_source().contains("table("));
    }
}
